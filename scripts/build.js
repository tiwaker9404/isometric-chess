// build.js: replays the game, writes docs/index.html (self-contained viewer) and docs/figures/*.svg
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { replay } from '../src/game.js';
import { SANS, NOTES, TITLE, SUBTITLE } from '../src/opera.js';
import * as iso from '../src/iso.js';
import { buildTimeline, poseAt } from '../src/timeline.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => fs.readFileSync(path.join(root, f), 'utf8');
const frames = replay(SANS);

// the viewer inlines the engine: strip ES-module syntax so it runs as a classic script
const engine = ['src/iso.js', 'src/timeline.js'].map(f => rd(f).replace(/^export /gm, '')).join('\n');
const data = { title: TITLE, subtitle: SUBTITLE, frames, notes: NOTES,
  outro: 'Every frame here is generated by code: a hand-written isometric SVG renderer with lathed pieces and no 3D engine.' };
fs.mkdirSync(path.join(root, 'docs/figures'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/index.html'), rd('src/viewer.html').replace('/*__ENGINE__*/', () => engine).replace('/*__DATA__*/', () => JSON.stringify(data)));

// static figures: the moments where the explanation clicks
const tl = buildTimeline(frames, NOTES);
const figs = { 'fig-1-pin': 6, 'fig-2-double-attack': 13, 'fig-3-bishop-pin': 17, 'fig-4-queen-sacrifice': 31, 'fig-5-checkmate': 33 };
for (const [name, ply] of Object.entries(figs)) {
  const seg = tl.segs[ply - 1], pose = poseAt(tl, frames, NOTES, seg.t2 - .01, iso.sqToXY);
  pose.scene.arrowAlpha = 1; pose.scene.arrows = NOTES[ply]?.arrows || []; pose.scene.marks = NOTES[ply]?.marks || [];
  fs.writeFileSync(path.join(root, `docs/figures/${name}.svg`), iso.renderScene(pose.scene, { bg: true }));
}
console.log(`built docs/index.html (${frames.length - 1} plies, ${tl.total.toFixed(1)}s) and ${Object.keys(figs).length} figures`);
